"""Generates rtl_custom/menu_font_rom.v (16x16 glyph ROM) and rtl_custom/menu_text_rom.v (text tables)."""
from PIL import Image, ImageDraw, ImageFont
import os
ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
TTF = "C:/Windows/Fonts/simhei.ttf"
if not os.path.exists(TTF): TTF = "C:/Windows/Fonts/simhei.ttf"
CN = "帧源抓拍识别中值显示实时冻结槽轮播执行开关分屏原图边缘阈缓存已"
chars = [' '] + list("0123456789") + ['/'] + list(CN)       # glyph id = index
gid = {c: i for i, c in enumerate(chars)}
def render(ch, size=16, thr=110):
    f = ImageFont.truetype(TTF, size)
    im = Image.new('L', (size, size), 0); d = ImageDraw.Draw(im)
    if ch == ' ': return [[0]*size for _ in range(size)]
    bb = d.textbbox((0, 0), ch, font=f); w, h = bb[2]-bb[0], bb[3]-bb[1]
    d.text(((size-w)//2 - bb[0], (size-h)//2 - bb[1]), ch, font=f, fill=255)
    px = im.load()
    return [[1 if px[x, y] >= thr else 0 for x in range(size)] for y in range(size)]
L = ["`timescale 1ns/1ps", "// Generated by sim/menu/gen_menu.py - 16x16 glyphs, id order: blank 0-9 / " + CN.encode('unicode_escape').decode(),
     "module menu_font_rom (input wire [5:0] ch, input wire [3:0] row, output reg [15:0] bits);",
     "always @* begin", "    case ({ch, row})"]
for i, c in enumerate(chars):
    g = render(c)
    for r in range(16):
        v = 0
        for x in range(16):
            if g[r][x]: v |= 1 << (15 - x)
        if v: L.append("    10'd%d: bits = 16'h%04x;" % (i*16 + r, v))
L += ["    default: bits = 16'h0000;", "    endcase", "end", "endmodule", ""]
open(os.path.join(ROOT, 'rtl_custom', 'menu_font_rom.v'), 'w', encoding='utf-8').write('\n'.join(L))

# ---------------- text tables ----------------
labels = ["帧源", "抓拍", "识别", "中值", "显示"]
values = {0: ["实时", "冻结", "槽1", "槽2", "槽3", "槽4", "轮播"],
          1: ["执行"],
          2: ["关", "开"], 3: ["关", "开"],
          4: ["分屏", "原图", "边缘"]}
def G(c): return gid[c]
def expr_choice(opts):
    # opts: list of glyph ids indexed by val
    if len(set(opts)) == 1: return str(opts[0])
    e = str(opts[-1])
    for i in range(len(opts)-2, -1, -1): e = "(val==3'd%d) ? 6'd%d : (%s)" % (i, opts[i], e)
    return e
rows = []   # (item,line,chr,expr,dim_expr)
for it in range(5):
    for i, c in enumerate(labels[it]): rows.append((it, 0, i, "6'd%d" % G(c), "1'b0"))
    vs = values[it]
    maxlen = max(len(v) for v in vs)
    for pos in range(maxlen):
        opts = [G(v[pos]) if pos < len(v) else 0 for v in vs]
        rows.append((it, 1, pos, "6'd" + expr_choice(opts) if len(set(opts)) == 1 else expr_choice(opts), "1'b0"))
def digit_expr(var, n):   # glyph of (var+1) for var in 0..n-1
    return expr_choice([G(str(k+1)) for k in range(n)]).replace("val", var)
# status line
for i, c in enumerate("阈值"): rows.append((0, 2, i, "6'd%d" % G(c), "1'b0"))
rows.append((0, 2, 3, digit_expr("thr", 6), "1'b0"))
rows.append((0, 2, 4, "6'd%d" % G('/'), "1'b0"))
rows.append((0, 2, 5, "6'd%d" % G('6'), "1'b0"))
for i, c in enumerate("缓存"): rows.append((1, 2, i, "6'd%d" % G(c), "1'b0"))
for k in range(4): rows.append((1, 2, 3+k, "6'd%d" % G(str(k+1)), "~valid[%d]" % k))
for i, c in enumerate("已存"): rows.append((2, 2, i, "(flash!=3'd0) ? 6'd%d : 6'd0" % G(c), "1'b0"))
rows.append((2, 2, 2, "(flash!=3'd0) ? 6'd%d : 6'd0" % G('槽'), "1'b0"))
rows.append((2, 2, 3, "(flash==3'd0) ? 6'd0 : (" + digit_expr("flash-3'd1", 4).replace("(val", "(flash-3'd1") + ")", "1'b0"))
T = ["`timescale 1ns/1ps", "// Generated by sim/menu/gen_menu.py - text tables of the menu bar",
     "// item 0..4, line 0 label / 1 value / 2 status, chr 0..11.  val = current value of the item.",
     "module menu_text_rom (input wire [2:0] item, input wire [1:0] line, input wire [3:0] chr,",
     "    input wire [2:0] val, thr, flash, input wire [3:0] valid,",
     "    output reg [5:0] glyph, output reg dim);",
     "always @* begin", "    glyph = 6'd0; dim = 1'b0;", "    case ({item, line, chr})"]
for it, ln, ch, e, d in rows:
    T.append("    {3'd%d, 2'd%d, 4'd%d}: begin glyph = %s; dim = %s; end" % (it, ln, ch, e, d))
T += ["    default: begin end", "    endcase", "end", "endmodule", ""]
open(os.path.join(ROOT, 'rtl_custom', 'menu_text_rom.v'), 'w', encoding='utf-8').write('\n'.join(T))
print(len(chars), 'glyphs', len(rows), 'text entries')
