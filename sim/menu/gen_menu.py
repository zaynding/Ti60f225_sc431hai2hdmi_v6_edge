"""Generates menu_font32.mem, rtl_custom/menu_font_rom.v and rtl_custom/menu_text_rom.v.
Glyphs are native 32x32.  Latin text and the "d/" threshold digits are packed two characters per 32-pixel cell."""
from PIL import Image, ImageDraw, ImageFont
import os
ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
TTF = "C:/Windows/Fonts/simhei.ttf"
FONT = ImageFont.truetype(TTF, 32)
THR = 120
names = [' ']                                   # glyph id = index (0 = blank)
def G(name):
    if name not in names: names.append(name)
    return names.index(name)
def tokens(s):
    if s.isascii() and s.isalpha():              # Latin word -> two characters per cell
        return [s[i:i+2].ljust(2) for i in range(0, len(s), 2)]
    return list(s)
labels = ["帧源", "抓拍", "识别", "算法", "显示"]
values = {0: ["实时", "冻结", "槽1", "槽2", "槽3", "槽4", "轮播"], 1: ["执行"], 2: ["关", "开"],
          3: ["Sobel", "Canny", "对比"], 4: ["分屏", "原图", "边缘"]}
def expr_choice(opts):
    if len(set(opts)) == 1: return "6'd%d" % opts[0]
    e = "6'd%d" % opts[-1]
    for i in range(len(opts)-2, -1, -1): e = "(val==3'd%d) ? 6'd%d : (%s)" % (i, opts[i], e)
    return e
rows = []                                        # (item, line, chr, glyph expression, dim expression)
for it in range(5):
    for i, t in enumerate(tokens(labels[it])): rows.append((it, 0, i, "6'd%d" % G(t), "1'b0"))
    vt = [tokens(v) for v in values[it]]
    for pos in range(max(len(v) for v in vt)):
        rows.append((it, 1, pos, expr_choice([G(v[pos]) if pos < len(v) else 0 for v in vt]), "1'b0"))
for i, c in enumerate("阈值"): rows.append((0, 2, i, "6'd%d" % G(c), "1'b0"))
e = "6'd%d" % G("6/")
for k in range(4, -1, -1): e = "(thr==3'd%d) ? 6'd%d : (%s)" % (k, G("%d/" % (k+1)), e)
rows.append((0, 2, 2, "(thr==3'd6) ? 6'd%d : (%s)" % (G("自"), e), "1'b0"))
rows.append((0, 2, 3, "(thr==3'd6) ? 6'd%d : 6'd%d" % (G("动"), G("6 ")), "1'b0"))
for i, c in enumerate("缓存"): rows.append((1, 2, i, "6'd%d" % G(c), "1'b0"))
for k in range(4): rows.append((1, 2, 2+k, "6'd%d" % G(str(k+1)), "~valid[%d]" % k))
for i, c in enumerate("已存槽"): rows.append((2, 2, i, "(flash!=3'd0) ? 6'd%d : 6'd0" % G(c), "1'b0"))
f = "6'd%d" % G("4")
for k in (2, 1, 0): f = "(flash==3'd%d) ? 6'd%d : (%s)" % (k+1, G(str(k+1)), f)
rows.append((2, 2, 3, "(flash==3'd0) ? 6'd0 : (" + f + ")", "1'b0"))
for i, t in enumerate(tokens('Sobel')): rows.append((5, 0, i, "6'd%d" % G(t), "1'b0"))
for i, t in enumerate(tokens('Canny')): rows.append((6, 0, i, "6'd%d" % G(t), "1'b0"))
assert len(names) <= 64, len(names)

def render_single(ch):
    im = Image.new('L', (32, 32), 0); d = ImageDraw.Draw(im)
    bb = d.textbbox((0, 0), ch, font=FONT); w, h = bb[2]-bb[0], bb[3]-bb[1]
    d.text(((32-w)//2 - bb[0], (32-h)//2 - bb[1]), ch, font=FONT, fill=255)
    return im
def render_pair(s):
    im = Image.new('L', (32, 32), 0); d = ImageDraw.Draw(im)
    for k, ch in enumerate(s):
        if ch == ' ': continue
        w = FONT.getlength(ch)
        d.text((16*k + (16-w)/2, 28), ch, font=FONT, fill=255, anchor='ls')
    return im
mem = []
for i in range(64):
    if i >= len(names) or names[i] == ' ': im = Image.new('L', (32, 32), 0)
    else: im = render_pair(names[i]) if len(names[i]) == 2 else render_single(names[i])
    px = im.load()
    for r in range(32):
        v = 0
        for x in range(32):
            if px[x, r] >= THR: v |= 1 << (31 - x)
        mem.append(v)
open(os.path.join(ROOT, 'menu_font32.mem'), 'w').write(chr(10).join('%08x' % v for v in mem) + chr(10))
open(os.path.join(ROOT, 'rtl_custom', 'menu_font_rom.v'), 'w', encoding='utf-8').write("""`timescale 1ns/1ps
// 32x32 glyph ROM held in one block-RAM (initialised from menu_font32.mem in the project root).
// Glyph order: see sim/menu/gen_menu.py.  addr = {glyph[5:0], row[4:0]}; 1-clock read latency.
module menu_font_rom (
    input  wire        clk,
    input  wire [10:0] addr,
    output wire [31:0] bits
);
simple_dual_port_ram #(.DATA_WIDTH(32), .ADDR_WIDTH(11), .OUTPUT_REG("FALSE"), .RAM_INIT_FILE("menu_font32.mem")) u_rom (
    .wdata(32'd0), .waddr(11'd0), .we(1'b0), .wclk(clk), .raddr(addr), .re(1'b1), .rclk(clk), .rdata(bits));
endmodule
""")
T = ["`timescale 1ns/1ps", "// Generated by sim/menu/gen_menu.py - text tables of the menu bar",
     "// item 0..4, line 0 label / 1 value / 2 status, chr 0..11.  val = current value of the item.",
     "module menu_text_rom (input wire [2:0] item, input wire [1:0] line, input wire [3:0] chr,",
     "    input wire [2:0] val, thr, flash, input wire [3:0] valid,",
     "    output reg [5:0] glyph, output reg dim);",
     "always @* begin", "    glyph = 6'd0; dim = 1'b0;", "    case ({item, line, chr})"]
for it, ln, ch, ex, d in rows:
    T.append("    {3'd%d, 2'd%d, 4'd%d}: begin glyph = %s; dim = %s; end" % (it, ln, ch, ex, d))
T += ["    default: begin end", "    endcase", "end", "endmodule", ""]
open(os.path.join(ROOT, 'rtl_custom', 'menu_text_rom.v'), 'w', encoding='utf-8').write('\n'.join(T))
print(len(names), 'glyphs', len(rows), 'text entries')
